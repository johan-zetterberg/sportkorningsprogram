/**
 * Translates common dressage terms within a string.
 */
export function translateDressageString(text, isInternational = false) {
    if (!text) return '';
    // Determine target lang based on user pref or competition mode
    const userPref = localStorage.getItem('user_lang_pref');
    const targetEn = (userPref === 'en') || isInternational;

    if (!targetEn) return text; // Keep Swedish if not target English

    let translated = text;

    // Sort terms by length (desc)
    const terms = Object.keys(DRESSAGE_TERMS).sort((a, b) => b.length - a.length);

    terms.forEach(term => {
        const replacement = DRESSAGE_TERMS[term];
        try {
            // Using Unicode Property Escapes for robust international word boundaries
            // (?<!\p{L}) matches a position NOT preceded by a letter
            // (?!\p{L}) matches a position NOT followed by a letter
            const regex = new RegExp(`(?<!\\p{L})${term}(?!\\p{L})`, 'giu');

            translated = translated.replace(regex, (match) => {
                // Preserve casing
                if (match === match.toUpperCase()) return replacement.toUpperCase();
                if (match[0] === match[0].toUpperCase() && match.slice(1) === match.slice(1).toLowerCase()) {
                    return replacement.charAt(0).toUpperCase() + replacement.slice(1);
                }
                return replacement.toLowerCase(); // Default to lowercase if input was lowercase
            });
        } catch (e) {
            // Fallback for environments without 'u' flag support (rare nowadays for target browsers)
            const regex = new RegExp(`\\b${term}\\b`, 'gi');
            translated = translated.replace(regex, replacement);
        }
    });

    return translated;
}

/**
 * Toggles the global language preference and reloads the page.
 */
export function toggleLanguage() {
    const current = localStorage.getItem('user_lang_pref') || 'sv';
    const next = current === 'en' ? 'sv' : 'en';
    localStorage.setItem('user_lang_pref', next);
    location.reload();
}

export function setLanguage(next) {
    const normalized = next === 'en' ? 'en' : 'sv';
    const current = localStorage.getItem('user_lang_pref') || 'sv';
    if (current === normalized) return;
    localStorage.setItem('user_lang_pref', normalized);
    location.reload();
}

