/**
 * Translates common dressage terms within a string.
 */
export function translateDressageString(text, isInternational = false) {
    if (!text) return '';
    // Determine target lang based on user pref or competition mode
    const userPref = localStorage.getItem('user_lang_pref');
    const targetEn = userPref ? (userPref === 'en') : Boolean(isInternational);

    if (!targetEn) return text; // Keep Swedish if not target English

    let translated = text;

    // Sort terms by length (desc)
    const terms = Object.keys(DRESSAGE_TERMS).sort((a, b) => b.length - a.length);

    terms.forEach(term => {
        const replacement = DRESSAGE_TERMS[term];
        try {
            // Using Unicode Property Escapes for robust international word boundaries
            // (?<!\p{L}) matches a position NOT preceded by a letter
            // (?!\p{L}) matches a position NOT followed by a letter
            const regex = new RegExp(`(?<!\\p{L})${term}(?!\\p{L})`, 'giu');

            translated = translated.replace(regex, (match) => {
                // Preserve casing
                if (match === match.toUpperCase()) return replacement.toUpperCase();
                if (match[0] === match[0].toUpperCase() && match.slice(1) === match.slice(1).toLowerCase()) {
                    return replacement.charAt(0).toUpperCase() + replacement.slice(1);
                }
                return replacement.toLowerCase(); // Default to lowercase if input was lowercase
            });
        } catch (e) {
            // Fallback for environments without 'u' flag support (rare nowadays for target browsers)
            const regex = new RegExp(`\\b${term}\\b`, 'gi');
            translated = translated.replace(regex, replacement);
        }
    });

    return translated;
}

/**
 * Toggles the global language preference and reloads the page.
 */
export function toggleLanguage() {
    const current = getCurrentLanguage();
    const next = current === 'en' ? 'sv' : 'en';
    localStorage.setItem('user_lang_pref', next);
    location.reload();
}

export function setLanguage(next) {
    const normalized = next === 'en' ? 'en' : 'sv';
    const current = getCurrentLanguage();
    const hasExplicitPref = localStorage.getItem('user_lang_pref') === normalized;
    if (current === normalized && hasExplicitPref) return;
    localStorage.setItem('user_lang_pref', normalized);
    location.reload();
}

/**
 * Initializes the language toggle button state.
 */
export function initLanguageToggle() {
    const host = document.getElementById('langToggle');
    if (!host) return;

    const current = getCurrentLanguage();
    const isEn = current === 'en';

    const svFlag = `<svg xmlns="http://www.w3.org/2000/svg" class="h-4 w-6 rounded-sm shadow-sm" viewBox="0 0 16 10" aria-hidden="true">
        <rect width="16" height="10" fill="#006aa7"/>
        <rect width="2" height="10" x="5" fill="#fecc00"/>
        <rect width="16" height="2" y="4" fill="#fecc00"/>
    </svg>`;

    const enFlag = `<svg xmlns="http://www.w3.org/2000/svg" class="h-4 w-6 rounded-sm shadow-sm" viewBox="0 0 60 30" aria-hidden="true">
        <clipPath id="t"><path d="M30,15h30v15zv15h-30zh-30v-15zv-15h30z"/></clipPath>
        <path d="M0,0v30h60v-30z" fill="#00247d"/>
        <path d="M0,0l60,30m0-30l-60,30" stroke="#fff" stroke-width="6"/>
        <path d="M0,0l60,30m0-30l-60,30" clip-path="url(#t)" stroke="#cf142b" stroke-width="4"/>
        <path d="M30,0v30m-30-15h60" stroke="#fff" stroke-width="10"/>
        <path d="M30,0v30m-30-15h60" stroke="#cf142b" stroke-width="6"/>
    </svg>`;

    host.innerHTML = `
      <button type="button"
        class="lang-flag-btn ${!isEn ? 'is-active' : ''}"
        data-lang="sv"
        title="Svenska"
        aria-label="Svenska" lang="sv"
        aria-pressed="${!isEn}">
        ${svFlag}
      </button>
      <button type="button"
        class="lang-flag-btn ${isEn ? 'is-active' : ''}"
        data-lang="en"
        title="English"
        aria-label="English" lang="en"
        aria-pressed="${isEn}">
        ${enFlag}
      </button>
    `;

    host.querySelectorAll('.lang-flag-btn').forEach((btn) => {
        btn.onclick = (e) => {
            e.preventDefault();
            setLanguage(btn.dataset.lang);
        };
    });
}
